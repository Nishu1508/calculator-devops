<#
  One-time local setup for the Jenkins container.
  Writes jenkins/.env (non-secret settings) and jenkins/secrets/* (passwords/tokens).
  Both are listed in .gitignore and are never committed.

  Usage:  powershell -ExecutionPolicy Bypass -File jenkins\setup-secrets.ps1
#>
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$secretsDir = Join-Path $here 'secrets'
New-Item -ItemType Directory -Force $secretsDir | Out-Null

function Read-Plain([string]$prompt, [string]$default) {
    $v = Read-Host "$prompt$(if ($default) { " [$default]" })"
    if ([string]::IsNullOrWhiteSpace($v)) { $default } else { $v.Trim() }
}

function Read-Secret([string]$prompt) {
    $s = Read-Host $prompt -AsSecureString
    $p = [Runtime.InteropServices.Marshal]::PtrToStringBSTR([Runtime.InteropServices.Marshal]::SecureStringToBSTR($s))
    $p.Trim()
}

function Write-Secret([string]$name, [string]$value) {
    if ([string]::IsNullOrEmpty($value)) { Write-Host "  (skipped $name - keeping existing value)" -ForegroundColor DarkYellow; return }
    # No trailing newline: Jenkins reads the file content as-is.
    [IO.File]::WriteAllText((Join-Path $secretsDir $name), $value)
}

Write-Host "`n=== Jenkins setup for the Calculator CI/CD pipeline ===`n" -ForegroundColor Cyan

$existing = @{}
$envFile = Join-Path $here '.env'
if (Test-Path $envFile) {
    Get-Content $envFile | Where-Object { $_ -match '^\s*([^#=]+)=(.*)$' } | ForEach-Object { $existing[$Matches[1].Trim()] = $Matches[2].Trim() }
}

$githubRepo = Read-Plain 'GitHub repository URL'           ($existing['GITHUB_REPO_URL'],   'https://github.com/Nishu1508/calculator-devops' | Where-Object { $_ } | Select-Object -First 1)
$dockerUser = Read-Plain 'Docker Hub username'             ($existing['DOCKERHUB_USERNAME'] | Where-Object { $_ })
$smtpUser   = Read-Plain 'Gmail address that SENDS mail'   ($existing['SMTP_USERNAME'],     'nishumalik208@gmail.com' | Where-Object { $_ } | Select-Object -First 1)
$notify     = Read-Plain 'Email that RECEIVES build mails' ($existing['NOTIFY_EMAIL'],      $smtpUser | Where-Object { $_ } | Select-Object -First 1)
$adminId    = Read-Plain 'Jenkins admin username'          ($existing['JENKINS_ADMIN_ID'],  'admin' | Where-Object { $_ } | Select-Object -First 1)

@"
# Generated by setup-secrets.ps1 - NOT committed (see .gitignore)
GITHUB_REPO_URL=$githubRepo
DOCKERHUB_USERNAME=$($dockerUser.ToLower())
SMTP_USERNAME=$smtpUser
NOTIFY_EMAIL=$notify
JENKINS_ADMIN_ID=$adminId
JENKINS_URL=http://localhost:8080/
"@ | Set-Content -Path $envFile -Encoding ascii

Write-Host "`nSecrets (input is hidden; press Enter to keep the current value):" -ForegroundColor Cyan
Write-Secret 'jenkins_admin_password' (Read-Secret 'Jenkins admin password (choose one)')
Write-Secret 'dockerhub_token'        (Read-Secret 'Docker Hub access token (hub.docker.com > Account settings > Personal access tokens, Read & Write)')
Write-Secret 'smtp_app_password'      ((Read-Secret 'Gmail App Password (myaccount.google.com/apppasswords, 16 letters)') -replace '\s', '')

foreach ($n in 'jenkins_admin_password', 'dockerhub_token', 'smtp_app_password') {
    $f = Join-Path $secretsDir $n
    if (-not (Test-Path $f)) { [IO.File]::WriteAllText($f, 'NOT_SET') }
}

Write-Host "`nSaved. Now (re)start Jenkins so it picks up the values:" -ForegroundColor Green
Write-Host "  cd $here" ; Write-Host "  docker compose up -d --force-recreate jenkins`n"
